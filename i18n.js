window.applySiteLanguage = function applySiteLanguage(next) {
  const lang = next === "de" ? "de" : "en";
  const pack = window.SITE_I18N[lang];
  try {
    localStorage.setItem("ayush-lang", lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = pack[el.dataset.i18n];
    if (typeof value === "string") el.textContent = value;
  });
  const rotator = document.querySelector(".rotator");
  if (rotator) {
    const words = window.SITE_I18N.words[lang];
    rotator.dataset.words = JSON.stringify(words);
    rotator.dataset.rotIndex = "0";
    if (!rotator.classList.contains("out")) rotator.textContent = words[0];
  }
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const on = button.dataset.lang === lang;
    button.classList.toggle("on", on);
    button.setAttribute("aria-pressed", String(on));
  });
  document.title = lang === "de" ? "Ayush Tandon — Salesforce- & CTI-Ingenieur" : "Ayush Tandon — Salesforce & CTI Engineer";
};
